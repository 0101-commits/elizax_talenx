/* ============================================================
   ez_signal_persona.js — 주체별 렌즈 (`window.EZPersona`)

   왜 필요한가. 카탈로그의 `roles` 는 세 갈래뿐이다 —
   `["member"]` 40건 · `["leader"]` 72건 · `["hr","exec"]` 38건.
   그래서 **HR과 경영진이 똑같은 38건을 똑같은 순서로** 받았고, 조직장은
   팀장 40건과 상위조직장 32건을 한 덩어리로 받았다. 받는 신호가 같은데
   보는 자리가 다르면 "먼저 짚어 주는 것"이 어긋난다.

   무엇을 하는가. 신호를 **감추지 않는다**(카탈로그 열람은 150건 그대로).
   같은 목록을 그 사람이 그 자리에서 먼저 볼 순서로 **정렬**한다.

     경영진   조직 사이 목표 정렬이 흐트러진 지점        (T4 연결 불일치 · 조직 비교)
     HR       평가 편차·이상치 — 공정성 이슈 사전 경보   (T3 기준 이탈 · 평가 단계)
     조직원   체크인 시점, 유관 목표 변경               (T1 기한 · T5 변동)
     조직장   1:1 전에 볼 것 — 워크로드·진척            (T2 공백 · 면담·장애요인)

   어디에 걸리는가. `ez_signal_engine.js` 의 `live()`·`pending()` 정렬 한 곳.
   알림 탭·FAB 배지·선제 팝업·추천 질문이 모두 그 함수를 거치므로 표면마다
   따로 손대지 않는다. 이 파일이 없어도 엔진은 예전 순서로 그대로 돈다.

   화면에 내보내는 말은 `lens()` 의 `title`·`hint` 두 줄뿐이다 — 유형 코드
   (T1~T5)·단계 이름·점수는 사용자에게 쓰지 않는다(R2 금지 표현 유지).
   ============================================================ */
(function () {
  'use strict';

  var LENS = {
    member: {
      title: '내 차례인 일',
      hint: '체크인할 때가 됐는지, 내 목표에 영향 주는 변경이 있는지 먼저 봐요',
      stage: { 중간점검: 3, 목표수립: 2, 평가: 1, 피드백: 1 },
      type: { T1: 3, T5: 3, T2: 2, T3: 1, T4: 1 },
      words: [['체크인', 3], ['상위 목표', 3], ['마감', 2], ['남았', 2], ['확신도', 1], ['내 목표', 2]]
    },
    leader: {
      title: '1:1 전에 볼 것',
      hint: '팀원 워크로드와 목표 진척을 묶어 이야기할 지점을 먼저 봐요',
      stage: { 중간점검: 3, 피드백: 2, 평가: 2, 목표수립: 2 },
      type: { T2: 3, T3: 2, T5: 2, T1: 2, T4: 1 },
      words: [['1on1', 3], ['면담', 3], ['장애요인', 2], ['확신도', 2], ['초과근무', 2], ['팀원', 1]]
    },
    hr: {
      title: '공정성 먼저',
      hint: '평가 편차와 이상치를 먼저 짚어 공정성 이슈를 미리 알려요',
      stage: { 평가: 3, 피드백: 2, 목표수립: 1, 중간점검: 1 },
      type: { T3: 3, T2: 2, T1: 2, T5: 1, T4: 1 },
      words: [['등급', 3], ['분포', 3], ['상한', 2], ['근거', 2], ['제출', 2], ['기준', 2],
              ['편차', 3], ['평가자', 2], ['가중치', 1]]
    },
    exec: {
      title: '목표 정렬 먼저',
      hint: '조직 사이 목표 정렬이 흐트러진 지점을 먼저 짚어요',
      stage: { 목표수립: 3, 중간점검: 3, 평가: 1, 피드백: 1 },
      type: { T4: 3, T5: 2, T3: 2, T1: 1, T2: 1 },
      words: [['정렬', 3], ['미연결', 3], ['상위 목표', 3], ['전략', 3], ['본부', 2],
              ['조직', 2], ['전사', 2], ['하위', 2], ['격차', 2]]
    }
  };

  function lens(role) { return LENS[role] || LENS.member; }

  /* rank — 클수록 먼저. 단계·유형은 무게 2배, 낱말은 알림 문구+판단 조건에서 센다. */
  function rank(sig, role) {
    if (!sig) return 0;
    var L = lens(role), n = 0, i;
    n += (L.stage[sig.stage] || 0) * 2;
    n += (L.type[sig.type] || 0) * 2;
    var hay = String(sig.notice || '') + ' ' + String(sig.principle || '');
    for (i = 0; i < L.words.length; i++) {
      if (hay.indexOf(L.words[i][0]) >= 0) n += L.words[i][1];
    }
    /* 도움 정도(카탈로그 score.help 1~3)를 마지막 가늠으로 — 동점을 가른다 */
    n += ((sig.score && sig.score.help) || 0);
    return n;
  }

  /* 엔진이 부르는 비교 함수. 순위 같으면 예전 순서(주체 → 단계 → 번호)를 그대로 쓴다. */
  function compare(a, b, role) {
    var d = rank(b, role) - rank(a, role);
    if (d) return d;
    if ((a.actorNo || 0) !== (b.actorNo || 0)) return (a.actorNo || 0) - (b.actorNo || 0);
    if ((a.stageNo || 0) !== (b.stageNo || 0)) return (a.stageNo || 0) - (b.stageNo || 0);
    return (a.no || 0) - (b.no || 0);
  }

  window.EZPersona = { lens: lens, rank: rank, compare: compare, LENS: LENS };
})();
